#!/usr/bin/env python3
"""Small, explicit format bridge used by the benchmark adapters.

The benchmark's comparison contract is deliberately ordinary (no gradients):
VMEC namelists/JSON, GVEC parameter files, GEQDSK and SPEC HDF5 are treated as
interchange formats, while every conversion records what it can and cannot
preserve.  Heavy code-specific converters are invoked only when installed.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path


def vmec_to_common(path: Path) -> dict:
    text = path.read_text(errors="replace")
    out: dict = {"format": "vmec_indata", "source": str(path), "scalars": {}, "boundary": []}
    for key, value in re.findall(r"(?im)^\s*([A-Za-z][A-Za-z0-9_]*)\s*=\s*([^!\n/]+)", text):
        value = value.strip().strip(",")
        if value.startswith(("'", '"')):
            parsed: object = value.strip("'\"")
        elif re.fullmatch(r"[TtFf]", value):
            parsed = value.upper() == "T"
        else:
            tokens = value.split()
            try:
                parsed_values = [float(token.replace("D", "E").replace("d", "e")) for token in tokens]
                parsed = parsed_values[0] if len(parsed_values) == 1 else parsed_values
                if isinstance(parsed, float) and parsed.is_integer():
                    parsed = int(parsed)
                elif isinstance(parsed, list):
                    parsed = [int(item) if item.is_integer() else item for item in parsed]
            except ValueError:
                parsed = value
        out["scalars"][key.upper()] = parsed
    for key, m, n, value in re.findall(
        r"(?im)^\s*(RBC|ZBS|RBS|ZBC)\s*\(\s*(-?\d+)\s*,\s*(-?\d+)\s*\)\s*=\s*([+\-0-9.eEdD]+)",
        text,
    ):
        out["boundary"].append({"field": key.upper(), "m": int(m), "n": int(n), "value": float(value.replace("D", "E").replace("d", "e"))})
    return out


def common_to_vmec(common: dict, path: Path) -> None:
    lines = ["&INDATA"]
    for key, value in common.get("scalars", {}).items():
        if isinstance(value, bool):
            value = "T" if value else "F"
        elif isinstance(value, list):
            value = " ".join(str(item) for item in value)
        elif isinstance(value, str):
            value = repr(value)
        lines.append(f" {key} = {value}")
    for item in common.get("boundary", []):
        lines.append(f" {item['field']}({item['m']},{item['n']}) = {item['value']:.16g}")
    lines.append("/")
    path.write_text("\n".join(lines) + "\n")


def geqdsk_summary(path: Path) -> dict:
    try:
        from freeqdsk import geqdsk  # type: ignore
    except ImportError as exc:
        raise SystemExit("GEQDSK conversion needs freeqdsk in the selected uv environment") from exc
    with path.open() as handle:
        data = geqdsk.read(handle)
    return {"format": "geqdsk", "source": str(path), "dimension": 2, "nx": int(data.nx), "ny": int(data.ny),
            "plasma_current": float(data.cpasma), "pressure_axis": float(data.pres[0])}


def spec_summary(path: Path) -> dict:
    try:
        import h5py  # type: ignore
    except ImportError as exc:
        raise SystemExit("SPEC conversion needs h5py in the selected uv environment") from exc
    with h5py.File(path, "r") as handle:
        datasets = []
        handle.visititems(lambda name, obj: datasets.append(name) if isinstance(obj, h5py.Dataset) else None)
    return {"format": "spec_hdf5", "source": str(path), "dimension": 3, "datasets": datasets,
            "note": "SPEC is an MRxMHD solver; no lossless VMEC WOUT conversion is claimed."}


def common_to_geqdsk(common: dict, path: Path) -> None:
    try:
        import numpy as np  # type: ignore
        from freeqdsk import geqdsk  # type: ignore
    except ImportError as exc:
        raise SystemExit("GEQDSK conversion needs numpy and freeqdsk") from exc
    nx = ny = 33
    current = float(common.get("plasma_current", common.get("scalars", {}).get("CURTOR", 0.0)))
    pressure = float(common.get("pressure_axis", 0.0))
    data = {"nx": nx, "ny": ny, "rdim": 1.6, "zdim": 2.4, "rcentr": 1.0,
            "rleft": 0.8, "zmid": 0.0, "rmagx": 1.6, "zmagx": 0.0,
            "simagx": 0.0, "sibdry": 1.0, "bcentr": 1.0, "cpasma": current,
            "fpol": np.ones(nx), "pres": np.full(nx, pressure),
            "psi": np.zeros((nx, ny)), "qpsi": np.ones(nx)}
    with path.open("w") as handle:
        geqdsk.write(data, handle, label="COMMON-GEQ")


def common_to_native_template(common: dict, path: Path, spectre: bool) -> None:
    scalars = common.get("scalars", {})
    nfp = int(scalars.get("NFP", 1))
    lines = ["! Generated by benchmark_vmec/tools/convert_equilibrium.py",
             "&physicslist" if not spectre else "[physics]",
             f" Nfp = {nfp}" if not spectre else f"nfp = {nfp}",
             " Igeometry = 3" if not spectre else "igeometry = 3",
             " Nvol = 1" if not spectre else "nvol = 1",
             " Mpol = 4" if not spectre else "mpol = 4",
             " Ntor = 2" if not spectre else "ntor = 2"]
    if spectre:
        lines.append("lfreebound = false")
        lines.append("phiedge = 1.0")
    else:
        lines.append(" phiedge = 1")
        lines.append("/")
    path.write_text("\n".join(lines) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Convert ordinary equilibrium files to or from benchmark metadata.",
        epilog=("Use to-common/from-common for canonical JSON. Optional code-specific "
                "converters are invoked only when their Python package is installed."),
    )
    parser.add_argument(
        "operation",
        choices=("to-common", "from-common", "vmec-to-gvec", "geqdsk-summary", "spec-summary"),
        help="conversion to perform",
    )
    parser.add_argument("source", help="input VMEC, GEQDSK, SPEC, or SPECTRE file")
    parser.add_argument("destination", nargs="?", help="output path (otherwise choose a suffix-based default)")
    args = parser.parse_args()
    source = Path(args.source)
    if args.operation == "to-common":
        if source.suffix.lower() == ".geqdsk":
            result = geqdsk_summary(source)
        elif source.suffix.lower() in (".sp", ".h5", ".hdf5"):
            result = spec_summary(source) if source.suffix.lower() != ".sp" else {
                "format": "spec_namelist", "source": str(source), "dimension": 3,
                "note": "SPEC native namelist; physical fields remain native."}
        elif source.suffix.lower() == ".toml":
            try:
                import tomllib
                result = {"format": "spectre_toml", "source": str(source), "data": tomllib.loads(source.read_text()), "dimension": 3}
            except ImportError:
                result = {"format": "spectre_toml", "source": str(source), "dimension": 3}
        else:
            result = vmec_to_common(source) if source.suffix.lower() != ".json" else json.loads(source.read_text())
        Path(args.destination or source.with_suffix(".common.json")).write_text(json.dumps(result, indent=2) + "\n")
    elif args.operation == "from-common":
        destination = Path(args.destination or source.with_suffix(".vmec"))
        common = json.loads(source.read_text())
        if destination.suffix.lower() == ".geqdsk":
            common_to_geqdsk(common, destination)
        elif destination.suffix.lower() == ".sp":
            common_to_native_template(common, destination, spectre=False)
        elif destination.suffix.lower() == ".toml":
            common_to_native_template(common, destination, spectre=True)
        else:
            common_to_vmec(common, destination)
    elif args.operation == "vmec-to-gvec":
        if not args.destination:
            parser.error("vmec-to-gvec requires a destination parameter.ini")
        subprocess.run(["pygvec", "convert-params", "--vmec", str(source), str(args.destination)], check=True)
    elif args.operation == "geqdsk-summary":
        result = geqdsk_summary(source)
        Path(args.destination or source.with_suffix(".json")).write_text(json.dumps(result, indent=2) + "\n")
    else:
        result = spec_summary(source)
        Path(args.destination or source.with_suffix(".json")).write_text(json.dumps(result, indent=2) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
